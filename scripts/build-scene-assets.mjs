// Bundles vgpu (MIT, Vercel Labs) for the design frame: one script that defines the global
// `vgpu` with the main API, `vgpu.scene`, `instanceGeometry` and `prepareShader`.
// Writes public/vgpu.js (downloads inline it), lib/vgpu-bundle.ts (the frame embeds it) and
// lib/vgpu-version.ts. Also collects the hand-tested starter scenes in lib/design/scenes/
// into lib/design/starter-scenes.ts for the agent's brief.
// Run after changing the vgpu version or the example: npm run build-scene-assets
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const version = JSON.parse(readFileSync("node_modules/vgpu/package.json", "utf8")).version;
const license = readFileSync("node_modules/vgpu/LICENSE", "utf8").trim();
const result = await build({
  stdin: {
    contents: [
      'export * from "vgpu";',
      'export * as scene from "vgpu/scene";',
      'export { instanceGeometry } from "vgpu/scene/gpu";',
      'export { prepareShader } from "@vgpu/wgsl/prepare";',
    ].join("\n"),
    resolveDir: process.cwd(),
  },
  bundle: true, format: "iife", globalName: "vgpu", minify: true, target: "es2022", platform: "browser",
  legalComments: "none", write: false,
});
const header = `/*! vgpu ${version} | ${license.split("\n").join("\n * ")} */\n`;
const code = header + result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
writeFileSync("public/vgpu.js", code);
writeFileSync("lib/vgpu-bundle.ts",
  `// Generated by scripts/build-scene-assets.mjs from vgpu ${version}. Do not edit.\n` +
  `export const VGPU_SCRIPT = ${JSON.stringify(code)};\n`);
writeFileSync("lib/vgpu-version.ts",
  `// Generated by scripts/build-scene-assets.mjs. Do not edit.\nexport const VGPU_VERSION = ${JSON.stringify(version)};\n`);
// Starter scenes: every lib/design/scenes/*.html, in name order, with its <title>.
const scenes = readdirSync("lib/design/scenes").filter((name) => name.endsWith(".html")).sort().map((file) => {
  const html = readFileSync(`lib/design/scenes/${file}`, "utf8").trim();
  return { name: file.replace(/\.html$/, ""), title: /<title>([^<]*)<\/title>/i.exec(html)?.[1].trim() ?? file, html };
});
writeFileSync("lib/design/starter-scenes.ts",
  `// Generated by scripts/build-scene-assets.mjs from lib/design/scenes/*.html. Do not edit.\n` +
  `export interface StarterScene { name: string; title: string; html: string }\n` +
  `export const STARTER_SCENES: StarterScene[] = ${JSON.stringify(scenes, null, 1)};\n`);
console.log(`starter scenes: ${scenes.map((scene) => `${scene.name} (${(scene.html.length / 1024).toFixed(0)} KB)`).join(", ")}`);
console.log(`vgpu ${version}: ${(code.length / 1024).toFixed(0)} KB`);
